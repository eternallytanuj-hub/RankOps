    md += `\n---\n\n`;

    md += `### 📈 4. Projected Business Impact & Traffic Forecast (90 Days)\n\n`;
    md += `- **AI Search Citation Lift**: Projected **+240% to +380% increase** in organic AI citations across Perplexity, ChatGPT Search, and Claude.\n`;
