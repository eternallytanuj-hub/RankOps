  /**
   * Calculates the Four-Pillar AI Discovery Breakdown metrics.
   */
  static calculateFourPillars(analysis = {}, patches = []) {
    const baseScore = analysis.auditScore || 54;
    const isPatched = patches.length > 0;

    const hasRobots = patches.some(p => p.filePath.includes('robots.txt'));
    const hasLlms = patches.some(p => p.filePath.includes('llms.txt'));
    const hasLlmsFull = patches.some(p => p.filePath.includes('llms-full.txt'));
    const hasHtml = patches.some(p => p.filePath.includes('index.html'));
    const hasSitemap = patches.some(p => p.filePath.includes('sitemap.xml'));

    return {
      perplexity: {
        name: 'Perplexity AI Discovery Index',
        baseline: Math.min(60, Math.round(baseScore * 0.85)),
        projected: isPatched && hasRobots ? 98 : 65,
        status: isPatched && hasRobots ? 'OPTIMAL' : 'AT RISK',
        keyFactors: 'Explicit PerplexityBot permissions & /llms.txt semantic index.'
      },
      chatgpt: {
        name: 'ChatGPT & OpenAI Search Readiness',
        baseline: Math.min(65, Math.round(baseScore * 0.9)),
        projected: isPatched && hasLlms ? 96 : 70,
        status: isPatched && hasLlms ? 'OPTIMAL' : 'AT RISK',
        keyFactors: 'GPTBot, OAI-SearchBot approval & machine-readable llms.txt standard.'
      },
      claude: {
        name: 'Claude Agent Grounding Depth',
        baseline: Math.min(55, Math.round(baseScore * 0.8)),
        projected: isPatched && hasLlmsFull ? 95 : 60,
        status: isPatched && hasLlmsFull ? 'OPTIMAL' : 'AT RISK',
        keyFactors: 'ClaudeBot authorization & 128k+ extended context corpus in llms-full.txt.'
      },
      traditionalSeo: {
        name: 'Google & Bing Core Web Standards',
        baseline: Math.min(70, Math.round(baseScore * 1.05)),
        projected: isPatched && hasHtml && hasSitemap ? 96 : 75,
        status: isPatched && hasHtml ? 'OPTIMAL' : 'NEEDS ATTENTION',
        keyFactors: 'Multi-entity Schema.org JSON-LD graph, canonical tags & XML sitemap.'
      }
    };
  }

